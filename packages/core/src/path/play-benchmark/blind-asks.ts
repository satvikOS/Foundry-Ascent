/**
 * Asks to measure the matching on (the models benchmark, `play_matching`), each with the plays that would answer it. All
 * synthetic, written from what each play is for and not from its phrases: no phrase and no ask of the playbook's tests is
 * among them, and none may be copied into a phrase (a benchmark that was read into the rules measures nothing).
 */
export interface BlindAsk {
  /** How it is said: as students type, as a call transcribes it, in a second language, or in as few words as they can. */
  readonly voice: 'student' | 'spoken' | 'second_language' | 'blunt';
  readonly ask: string;
  /** Any of them is right; the first is the best. */
  readonly plays: readonly string[];
}

const ask = (voice: BlindAsk['voice'], text: string, ...plays: string[]): BlindAsk => ({
  voice,
  ask: text,
  plays,
});


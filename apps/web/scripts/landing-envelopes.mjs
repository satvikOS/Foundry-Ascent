#!/usr/bin/env node
/*
 * The landing page's device ad moves its voice presence and draws its timeline from recorded audio, never
 * from made-up numbers. This renders the ad's two spoken lines with a synthetic voice (macOS `say`, written
 * to a file, never played), measures each as 10 Hz RMS (100 ms bins of 16 kHz PCM, the same RMS the call's
 * playback analyser and microphone worklet report), and writes them to
 * src/components/landing/device-ad/envelopes.json. Run it on macOS when a line changes:
 *
 *   node apps/web/scripts/landing-envelopes.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'components', 'landing', 'device-ad', 'envelopes.json');
const content = JSON.parse(
  readFileSync(join(here, '..', 'src', 'components', 'landing', 'device-ad', 'session.json'), 'utf8'),
);

const RATE = 16_000;
const BIN = RATE / 10;

/** 16-bit little-endian mono samples from a WAVE file's `data` chunk. */
function samples(wav) {
  let offset = 12;
  while (offset + 8 <= wav.length) {
    const id = wav.toString('ascii', offset, offset + 4);
    const size = wav.readUInt32LE(offset + 4);
    if (id === 'data') {
      const data = wav.subarray(offset + 8, offset + 8 + size);
      const values = new Float32Array(Math.floor(data.length / 2));
      for (let i = 0; i < values.length; i += 1) values[i] = data.readInt16LE(i * 2) / 32_768;
      return values;
    }
    offset += 8 + size + (size % 2);
  }
  throw new Error('No data chunk in the rendered speech');
}

/** RMS per 100 ms, leading and trailing silence trimmed (a turn starts and ends with the voice). */
function envelope(pcm) {
  const bins = [];
  for (let start = 0; start + BIN <= pcm.length; start += BIN) {
    let sum = 0;
    for (let i = start; i < start + BIN; i += 1) sum += pcm[i] * pcm[i];
    bins.push(Number(Math.sqrt(sum / BIN).toFixed(4)));
  }
  const loud = (value) => value > 0.004;
  const first = bins.findIndex(loud);
  const last = bins.length - 1 - [...bins].reverse().findIndex(loud);
  return bins.slice(first, last + 1);
}

const dir = mkdtempSync(join(tmpdir(), 'landing-envelopes-'));
try {
  const result = {
    $comment: 'Generated by apps/web/scripts/landing-envelopes.mjs. 10 Hz RMS of a synthetic voice.',
    hz: 10,
  };
  for (const [speaker, line, voice] of [
    ['veir', content.call.veirLine, 'Daniel'],
    ['student', content.call.studentLine, 'Samantha'],
  ]) {
    const file = join(dir, `${speaker}.wav`);
    execFileSync('say', ['-v', voice, '-o', file, '--file-format=WAVE', `--data-format=LEI16@${RATE}`, line]);
    result[speaker] = envelope(samples(readFileSync(file)));
  }
  writeFileSync(out, `${JSON.stringify(result, null, 0)}\n`);
  process.stdout.write(`wrote ${String(result.veir.length)} + ${String(result.student.length)} bins\n`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
